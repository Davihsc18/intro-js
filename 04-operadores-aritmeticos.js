// Os operadores aritméticos são utilizados para realizar operações matemáticas, como por exemplo, somar, subtrair, multiplicar e dividir.

 const preco = 50;
 const frete = 15;

// 1 - Adição ( + )
// Utilizamos esse operador para a soma de valores
const soma = preco + frete

console.log(preco + frete)
console.log(15 + 10)
console.log(soma)


console.log("----------------")
// 2 - Subtração ( - )
// Utilizamos esse operador para realizar a subtração de valores
const subtracao = preco - frete

console.log(subtracao)
console.log(15 - 10);
console.log(preco - frete);

console.log("-------------");
// 3 - Multiplicação ( * )
// Utilizamos esse operador para realizar a multiplicação de valores
const multiplicacao = preco * frete

console.log (multiplicacao)
console.log (15 * 10);
console.log (preco * frete);

const preco2 = 25
const quantidade = 4

const total = preco2 * quantidade
console.log(total)

console.log("-------------");
// 4 - Divisão ( / )
// // Utilizamos esse operador para realizar a divisão de valores
const divisao = preco / frete

console.log(divisao);
console.log( preco / frete)
console.log( 10 / 2)
console.log( 10 / 0)

console.log("-------------");
// 5 - Exponenciação ( ** )
// Utilizamos esse operador para realizar para exponenciação de valores, ou seja, elevar um número a uma potência 
const exponenciacao = preco ** frete

console.log(exponenciacao)
console.log(2 ** 5)

console.log("-------------");
// 6 - Resto da divisão ( % )
// O operador % retorna o RESTO DA DIVISÃO, não o resultado em si.
// Utilizamos esse ordenar para verificar se um número é ímpar ou par.
console.log(8 % 2) // resto 0
console.log(7 % 2) // resto 1

console.log("-----------------");
// 7 - Incremento ( ++ )
// Esse operador serve para aumentar o valor de uma variavel em uma unidade ( 1 )
let contador = 5;

console.log(contador)

contador++
console.log(contador)

console.log("-----------------");

